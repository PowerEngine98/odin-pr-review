/**
 * 2πr for r = 6.2, to the precision a 13px circle can show. Both rings below
 * are drawn on this geometry, so the two sit at the same optical weight when
 * they end up side by side in the bar.
 */
const CIRCUMFERENCE = 38.96;

/** The dash pattern for an arc filled to a fraction of the circle. */
const arc = (filled: number): string => {
  const drawn = Math.max(0, Math.min(1, filled)) * CIRCUMFERENCE;
  return `${drawn.toFixed(2)} ${(CIRCUMFERENCE - drawn).toFixed(2)}`;
};

